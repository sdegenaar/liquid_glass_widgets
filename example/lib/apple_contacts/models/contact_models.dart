import 'package:flutter/cupertino.dart';

/// Data model representing a contact entry in Apple Contacts (iOS 26/27).
class ContactItem {
  ContactItem({
    required this.id,
    required this.firstName,
    required this.lastName,
    required this.phone,
    required this.email,
    required this.jobTitle,
    required this.company,
    required this.birthday,
    this.avatarColor = const Color(0xFF007AFF),
    this.isFavorite = false,
    this.emergencyContact = false,
    this.socialProfiles = const ['@apple', '@swiftlang'],
    List<DateTime>? milestoneDates,
  }) : milestoneDates = milestoneDates ?? [birthday];

  final String id;
  String firstName;
  String lastName;
  String phone;
  String email;
  String jobTitle;
  String company;
  DateTime birthday;
  Color avatarColor;
  bool isFavorite;
  bool emergencyContact;
  List<String> socialProfiles;
  List<DateTime> milestoneDates;

  String get displayName => '$firstName $lastName'.trim();
  String get initials =>
      '${firstName.isNotEmpty ? firstName[0] : ''}${lastName.isNotEmpty ? lastName[0] : ''}'
          .toUpperCase();

  ContactItem copyWith({
    String? id,
    String? firstName,
    String? lastName,
    String? phone,
    String? email,
    String? jobTitle,
    String? company,
    DateTime? birthday,
    Color? avatarColor,
    bool? isFavorite,
    bool? emergencyContact,
    List<String>? socialProfiles,
    List<DateTime>? milestoneDates,
  }) {
    return ContactItem(
      id: id ?? this.id,
      firstName: firstName ?? this.firstName,
      lastName: lastName ?? this.lastName,
      phone: phone ?? this.phone,
      email: email ?? this.email,
      jobTitle: jobTitle ?? this.jobTitle,
      company: company ?? this.company,
      birthday: birthday ?? this.birthday,
      avatarColor: avatarColor ?? this.avatarColor,
      isFavorite: isFavorite ?? this.isFavorite,
      emergencyContact: emergencyContact ?? this.emergencyContact,
      socialProfiles: socialProfiles ?? List.from(this.socialProfiles),
      milestoneDates: milestoneDates ?? List.from(this.milestoneDates),
    );
  }
}

